import { CourseList, CoursesOnGrid, GridPositionBase } from "../../types/types";
import { withoutCoreCourses } from "../../data/coreCourses";
import { getMembership, hasFlag } from "../../requirements/evaluate";
import { Curriculum } from "../../requirements/types";
import { PLAN_TERMS, PlanTerm } from "./parsePlan";

export interface PlannerAnswers {
  interests: string[]; // curriculum group ids the student ticked
  interestNotes: string;
  designation: "CE" | "EE" | "none"; // only used when designation is derived
  includeGrid: boolean; // send the current grid as the starting point
  lockedTerms: PlanTerm[]; // of 3F/3S/4F/4S; only used with includeGrid
  taken: string; // courses beyond the core taken before third year (XX)
  mustTake: string;
  avoid: string;
  notes: string;
}

export const groupWord = (curriculum: Curriculum) =>
  curriculum.id === "ece-pre2026" ? "Area" : "Group";

// Our own short descriptions, not official names
const newGroupHints = {
  A: "devices, electronics, energy, electromagnetics, photonics",
  B: "probability, control, communications, signal processing",
  C: "computer hardware, software, networks",
};
export const groupHints: Record<string, Record<string, string>> = {
  "ece-pre2026": {
    "1": "Photonics and Semiconductor Physics",
    "2": "Electromagnetics and Energy Systems",
    "3": "Analog and Digital Electronics",
    "4": "Control, Communications and Signal Processing",
    "5": "Computer Hardware and Computer Networks",
    "6": "Software",
  },
  "ele-2026": newGroupHints,
  "cpe-2026": newGroupHints,
};

/** "Area 5 (hint)", or just "Area 5" when there is no hint */
export const groupText = (curriculum: Curriculum, id: string) => {
  const group = curriculum.groups.find((g) => g.id === id);
  const base = `${groupWord(curriculum)} ${group?.label ?? id}`;
  const hint = groupHints[curriculum.id]?.[id];
  return hint ? `${base} (${hint})` : base;
};

// Stand-in cards from the default course list; they are not real courses
const PLACEHOLDERS = new Set(["AAA000", "CST000", "HSS000"]);

const formatReqs = (reqs: (string | string[])[]) =>
  reqs
    .map((req) => (Array.isArray(req) ? `(${req.join(" or ")})` : req))
    .join(" and ");

const catalogueLine = (
  curriculum: Curriculum,
  code: string,
  courses: CourseList
) => {
  const course = courses[code];
  const { groups, kernel } = getMembership(curriculum, code, course);
  const word = groupWord(curriculum);
  const group = groups.length
    ? `${word}${groups.length > 1 ? "s" : ""} ${groups.join(", ")}${kernel ? " kernel" : ""}`
    : "-";
  const terms = course.onlyF ? "F only" : course.onlyS ? "S only" : "F or S";
  const types = [
    hasFlag(curriculum, "isCS", code, course) && "CS",
    hasFlag(curriculum, "isHSS", code, course) && "HSS",
    hasFlag(curriculum, "isSciMath", code, course) && "Sci/Math",
    course.isArtSci && "ArtSci",
  ].filter(Boolean);
  const fields = [code, course.name, group, terms, types.join(", ") || "-"];
  const preq = withoutCoreCourses(course.preq);
  const coreq = withoutCoreCourses(course.coreq);
  if (preq.length) fields.push(`prereq: ${formatReqs(preq)}`);
  if (coreq.length) fields.push(`coreq: ${formatReqs(coreq)}`);
  return fields.join(" | ");
};

const gridLines = (coursesOnGrid: CoursesOnGrid) =>
  PLAN_TERMS.map((term) => {
    const codes = [1, 2, 3, 4, 5, 6]
      .map((slot) => coursesOnGrid[`${term}.${slot}` as GridPositionBase])
      .filter(Boolean);
    return `${term}: ${codes.length ? codes.join(", ") : "(empty)"}`;
  });

export const buildPrompt = ({
  answers,
  courses,
  coursesOnGrid,
  curriculum,
}: {
  answers: PlannerAnswers;
  courses: CourseList;
  coursesOnGrid: CoursesOnGrid;
  curriculum: Curriculum;
}): string => {
  const word = groupWord(curriculum);
  const derived =
    curriculum.designation.type === "derived" ? curriculum.designation : null;
  const sections: string[] = [];

  sections.push(
    `You are helping a University of Toronto Electrical and Computer Engineering
student plan their third- and fourth-year courses. Everything you need is
below. It was generated by ecepathmaker.com from the same data the site uses
to check plans. Use only this data for course codes, terms, groups and
prerequisites; do not rely on memory for them.

If something important is unclear, ask me up to three short questions first.
Otherwise go straight to the plan.`
  );

  sections.push(
    `## How a plan works
- Four terms: 3F (third-year fall), 3S (third-year winter), 4F, 4S.
- Normally 5 courses per term. A term can hold at most 6.
- At most 20 courses count toward the degree, including any in XX.
- XX holds courses I took before third year.
- First- and second-year core ECE courses are already done. Prerequisites they cover have been removed from the catalogue below.
- A prerequisite must be in an earlier term than the course. A corequisite must be in the same term or earlier. "(A or B)" means any one of them.
- If a prerequisite code is not in the catalogue, I cannot add it. Pick another option from its "or" group, or avoid the course, unless I say I have taken it.
- "F only" / "S only" courses can only go in fall / winter terms.
- The catalogue has only a few complementary studies (CS / HSS) electives. If the plan needs more than it offers, leave those slots out of the final block and tell me how many CS and HSS courses I still have to add myself.`
  );

  const reqLines = curriculum.requirements.map((rule) => {
    const line = `- ${rule.label}: ${rule.tooltip}`;
    if (rule.type !== "capstone") return line;
    // The tooltip does not name the courses or the timing
    const pairs = rule.pairs.map(([h1, h2]) => `${h1} + ${h2}`).join(", or ");
    return `${line}: ${pairs}. Put the two halves in different terms of year ${rule.year}. The site lists the second half as its own entry.`;
  });
  if (
    curriculum.requirements.some((r) =>
      ["slots", "areaBreadth", "areaDepth"].includes(r.type)
    )
  ) {
    reqLines.push(
      "- Breadth, depth, science/math and technical electives are exclusive: one course fills only one of them."
    );
  }
  reqLines.push("- HSS courses also count as CS (complementary studies).");
  if (derived) {
    const computer = derived.computerGroups
      .map((id) => curriculum.groups.find((g) => g.id === id)?.label ?? id)
      .join(", ");
    reqLines.push(
      `- Of the 8 breadth and depth courses, at least ${derived.ceMin} from ${word}s ${computer} gives Computer Engineering; at least ${derived.eeMin} from the other ${word.toLowerCase()}s gives Electrical Engineering.`
    );
  } else if (curriculum.designation.type === "fixed") {
    const program =
      curriculum.designation.value === "CE"
        ? "Computer"
        : curriculum.designation.value === "EE"
          ? "Electrical"
          : "Electrical and Computer";
    reqLines.push(`- This curriculum is the ${program} Engineering program.`);
  }
  sections.push(
    `## Graduation requirements (${curriculum.label})
${reqLines.join("\n")}
Not covered by this data, remind me to check them myself: ${curriculum.manualChecks}`
  );

  sections.push(
    `## ${word}s\n` +
      curriculum.groups
        .map((g) => {
          const hint = groupHints[curriculum.id]?.[g.id];
          return `- ${word} ${g.label}${hint ? `: ${hint}` : ""}`;
        })
        .join("\n")
  );

  sections.push(
    `## Course catalogue
Format: CODE | name | group | terms | type | prereq | coreq
` +
      Object.keys(courses)
        .filter((code) => !PLACEHOLDERS.has(code))
        .sort()
        .map((code) => catalogueLine(curriculum, code, courses))
        .join("\n")
  );

  const about: string[] = [];
  if (answers.interests.length) {
    about.push(
      `- Interested in: ${answers.interests
        .map((id) => groupText(curriculum, id))
        .join(", ")}`
    );
  }
  if (answers.interestNotes.trim()) {
    about.push(`- Also interested in: ${answers.interestNotes.trim()}`);
  }
  if (derived && answers.designation !== "none") {
    about.push(
      `- Goal: graduate as ${answers.designation === "CE" ? "Computer" : "Electrical"} engineering`
    );
  }
  // Always say what is in XX, so the AI does not have to ask
  const gridEmpty = Object.values(coursesOnGrid).every((code) => !code);
  const showGrid = answers.includeGrid && !gridEmpty;
  const xxOnGrid = [1, 2, 3, 4, 5, 6].some(
    (slot) => coursesOnGrid[`XX.${slot}` as GridPositionBase]
  );
  if (answers.taken.trim()) {
    about.push(
      `- Taken before third year (XX, these count toward the 20 and toward CS/HSS if they are CS/HSS): ${answers.taken.trim()}. Nothing else beyond the first- and second-year core.`
    );
  } else if (!(showGrid && xxOnGrid)) {
    about.push(
      "- Taken before third year (XX): nothing beyond the first- and second-year core, so 0 courses toward the 20 and 0 CS/HSS electives so far"
    );
  }
  if (answers.mustTake.trim()) about.push(`- Must take: ${answers.mustTake.trim()}`);
  if (answers.avoid.trim()) about.push(`- Avoid: ${answers.avoid.trim()}`);
  if (answers.notes.trim()) about.push(`- Other notes: ${answers.notes.trim()}`);
  if (about.length) sections.push(`## About me\n${about.join("\n")}`);

  if (showGrid) {
    const locked = answers.lockedTerms.filter((t) => t !== "XX");
    const keep = locked.length
      ? `Keep these terms exactly as they are: ${locked.join(", ")}. Always keep XX. You may change the other terms.`
      : "Always keep XX. You may change any other term.";
    sections.push(
      `## My current grid\n${gridLines(coursesOnGrid).join("\n")}\n${keep}`
    );
  }

  sections.push(
    `## What I want back
1. A recommended plan, term by term, with one short reason per course.
2. A checklist showing how the plan meets each graduation requirement.
3. Two or three alternatives or swaps (for example a different depth area, or a lighter term) and what each one changes.
4. Finish with the recommended plan in exactly this format, in one code block, using only course codes from the catalogue, all four terms listed:

3F: ECE302, ECE345, ...
3S: ...
4F: ...
4S: ...

I will paste that block back into ecepathmaker.com/plan, which checks it against the real requirements. Course offerings change, so remind me to confirm with the official calendar and my academic advisor.`
  );

  return sections.join("\n\n");
};
